const dictionaries = { hi, mr };

export function translate(text, language = "en", variables = {}) {
  const translated = dictionaries[language]?.[text] || text;
  return Object.entries(variables).reduce(
    (result, [key, value]) => result.replaceAll(`{{${key}}}`, String(value)),
    translated,
  );
}

export function useTranslation() {
  const language = useSettingsStore((state) => state.settings.language || "en");
  const t = useCallback((text, variables) => translate(text, language, variables), [language]);
  return { language, t };
}
